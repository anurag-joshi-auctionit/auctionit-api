export function buildServiceInvoicesExportFilename(): string {
  return "service-invoices-export.xlsx";
}

export async function buildServiceInvoicesExportXlsx(
  rows: ServiceInvoiceListRow[],
): Promise<Buffer> {
  return buildRowsXlsx({
    sheetName: "Service Invoices",
    creator: "AuctionIT",
    columns: EXPORT_COLUMNS,
    rows,
  });
}
